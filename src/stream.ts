export async function readStreamingResponse(res: Response , shouldStream : boolean = true) {

  // first check if the response actually has a body to read
  if (!res.body) {
    throw new Error("Response body is missing");
  }

  
  // this reader is used to consume the incoming stream chunk by chunk
  const reader = res.body.getReader();

  // this decoder converts the incoming bytes into readable text
  const decoder = new TextDecoder();

  // buffer stores the incoming chunks because they might not arrive as complete lines
  let buffer = "";

  // this stores the complete response generated by the model
  let content = "";

  // stores the reason why the model stopped generating the response
  let finishReason: string | null = null;

  // this map is used to store all the tool calls made by the agent
  // we use the index as the key because multiple tool calls can arrive in the same stream
  const toolCalls = new Map<number, any>();


  let tokenUsage = {

    prompt_tokens :0 ,
    completion_tokens : 0,
    total_tokens : 0 ,
  };

  // this function processes one complete SSE line at a time
  function processLine(line: string) {


  

    // we only care about lines that contain the actual data
    if (!line.startsWith("data:")) return;

    // remove the data prefix to extract the actual JSON response
    const rawData = line.slice(5).trim();

    // ignore empty data and the DONE signal sent when streaming is completed
    if (!rawData || rawData === "[DONE]") return;

    // convert the incoming JSON string into a JavaScript object
    let data: any;
    try {
      data = JSON.parse(rawData);
    } catch {
      return;
    }

    // check if the API has returned an error
    if (data.error) {
      throw new Error(data.error.message);
    }

    // extract the first choice from the response
    const choice = data.choices?.[0];

    // if there is no choice then there is nothing to process
    if (!choice) return;

    // delta contains the newly generated piece of information from the model
    const delta = choice.delta;


    // collect normal text generated by the model
    if (delta?.content) {

      // append every incoming text fragment to build the complete response
      content += delta.content;

      // print each incoming fragment directly to the terminal
      if(shouldStream){
      process.stdout.write(delta.content);
    }
  }


    // reconstruct tool calls because the model sends them in small fragments
    if (delta?.tool_calls) {

      // loop through all the tool calls received in the current delta
      for (const tool of delta.tool_calls) {

        // each tool call has an index which helps us identify it
        const index = tool.index ?? 0;

        // if this is a new tool call then create an entry for it in the map
        if (!toolCalls.has(index)) {
          toolCalls.set(index, {
            id: "",
            type: "function",
            function: {
              name: "",
              arguments: "",
            },
          });
        }

        // get the existing tool call so we can keep appending incoming fragments
        const existing = toolCalls.get(index);

        // the tool call id might arrive separately, so update it when received
        if (tool.id) existing.id = tool.id;

        // reconstruct the function name by appending each incoming fragment
        if (tool.function?.name) {
          existing.function.name += tool.function.name;
        }

        // reconstruct the arguments in the same way
        // these arguments might arrive as incomplete JSON fragments
        if (tool.function?.arguments) {
          existing.function.arguments += tool.function.arguments;
        }
      }
    }


    // capture the finish reason once the model has completed its generation
    if (choice.finish_reason) {
      finishReason = choice.finish_reason;
    }

    if(data.usage){
      tokenUsage = {
        prompt_tokens : data.usage.prompt_tokens ?? 0,
        completion_tokens : data.usage.completion_tokens ?? 0 ,
        total_tokens : data.usage.total_tokens ?? 0 ,
      };
    }
  }


  // now start reading the incoming stream continuously
  while (true) {

    // read the next chunk from the response stream
    const { done, value } = await reader.read();

    // if the stream is finished then exit the loop
    if (done) break;

    // convert the received bytes into readable text and append them to the buffer
    // stream: true makes sure incomplete characters are handled correctly
    buffer += decoder.decode(value, { stream: true });

    // split the buffer into individual lines
    // the regex handles both Windows (\r\n) and Unix (\n) line endings
    const lines = buffer.split(/\r?\n/);

    // remove the last element because it might be an incomplete line
    // save that incomplete part in the buffer for the next incoming chunk
    buffer = lines.pop() ?? "";

    // process every complete line received in the current chunk
    for (const line of lines) {
      processLine(line);
    }
  }


  // flush the decoder to process any remaining bytes
  buffer += decoder.decode();

  // if anything is still left in the buffer, process that final line
  if (buffer.trim()) {
    processLine(buffer);
  }


  // return the complete assistant response after reconstructing all the fragments
  return {
    role: "assistant",
    content: content || null,
    tool_calls: Array.from(toolCalls.values()),
    finish_reason: finishReason,
    usage  : tokenUsage,
  };
}